//! The golden bits (README, "Quantisation"): a table of raw samples and the image of the
//! sample a fresh quantiser makes of each, and a table of turns and the angles they leave,
//! pinned. Generated on aarch64-apple-darwin; CI's linux-x64 and windows-x64 tests (the
//! x86-64-v3 build) check the same table, so a target that quantises one raw sample to
//! different integers fails here. A mismatch prints the table of the target it ran on.

#![forbid(unsafe_code)]

use core::f32::consts::{FRAC_PI_2, FRAC_PI_4, PI, TAU};

use lactose_input::{Action, Actions, SAMPLE_SIZE};
use lactose_input_host::{Quantiser, RawSample};

fn raw(movement_x: f32, movement_y: f32, yaw: f32, pitch: f32, held: u32) -> RawSample {
    RawSample {
        movement_x,
        movement_y,
        yaw,
        pitch,
        held: Actions::from_bits(held),
        latched: Actions::EMPTY,
    }
}

/// The raw samples: in range, on the edges, past them, huge, tiny and non-finite.
#[allow(clippy::approx_constant, reason = "values near PI, E, PI/2 and TAU on purpose")]
fn samples() -> Vec<RawSample> {
    let jump_sprint = Actions::EMPTY.with(Action::Jump).with(Action::Sprint).bits();
    vec![
        RawSample::IDLE,
        raw(0.5, -0.5, 0.1, 0.2, jump_sprint),
        raw(1.0, 1.0, PI, -FRAC_PI_2, 1 << 16),
        raw(2.0, 0.0, -PI, FRAC_PI_2, u32::MAX),
        raw(0.3, 0.4, TAU + 0.1, 1.0, 0),
        raw(-core::f32::consts::FRAC_1_SQRT_2, core::f32::consts::FRAC_1_SQRT_2, -0.1, -1.0, 2),
        raw(1e30, -1e30, 1e6, 1e-3, 0),
        raw(f32::MAX, f32::MAX, -1e30, -1e-3, 0),
        raw(f32::NAN, 0.25, f32::NAN, f32::NAN, 0),
        raw(f32::INFINITY, f32::NEG_INFINITY, f32::INFINITY, f32::INFINITY, 0),
        raw(f32::MIN_POSITIVE, 1e-40, 3.141_59, -FRAC_PI_4, 0),
        raw(0.123_456, -0.654_321, 5.432_1, 0.000_1, 0),
        raw(-0.999, 0.044_7, -2.718_28, 1.570_7, 0),
        raw(0.6, 0.8, 1_234.567_8, -1.234_5, 0x8000_0001),
        raw(-0.000_015, 0.000_016, 0.000_047, -0.000_047, 0),
        raw(0.999_99, -0.004_47, -6.283_18, 2.5, 0),
    ]
}

/// A start `(yaw, pitch)`, then each `(delta_yaw, delta_pitch)` in order.
type Turns = (f32, f32, Vec<(f32, f32)>);

fn turns() -> Vec<Turns> {
    vec![
        (0.0, 0.0, vec![(0.37, 0.1); 100]),
        (3.0, 1.5, vec![(0.2, 0.2), (0.2, -0.2), (-6.5, 0.0)]),
        (-3.1, -1.0, vec![(-0.1, -1.0), (1e6, 0.5), (f32::NAN, 0.25)]),
        (PI.next_down(), 0.0, vec![(1.5e-7, 0.0)]),
        (1e30, 0.0, vec![(0.5, 0.0)]),
        (0.0, 0.0, vec![(0.000_4, 0.000_1); 5_000]),
    ]
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("0x{b:02x}")).collect::<Vec<_>>().join(", ")
}

#[test]
fn the_quantised_images_are_pinned() {
    let actual: Vec<[u8; SAMPLE_SIZE]> = samples()
        .into_iter()
        .map(|mut sample| Quantiser::new().next(&mut sample).to_sample_bytes())
        .collect();
    let printed: String = actual.iter().map(|row| format!("    [{}],\n", hex(row))).collect();
    assert_eq!(actual.as_slice(), IMAGES, "the table on this target:\n[\n{printed}]");
}

#[test]
fn the_turned_angles_are_pinned() {
    let actual: Vec<[u32; 2]> = turns()
        .into_iter()
        .map(|(yaw, pitch, deltas)| {
            let mut sample = RawSample { yaw, pitch, ..RawSample::IDLE };
            for (delta_yaw, delta_pitch) in deltas {
                sample.turn(delta_yaw, delta_pitch);
            }
            [sample.yaw.to_bits(), sample.pitch.to_bits()]
        })
        .collect();
    let printed: String =
        actual.iter().map(|[yaw, pitch]| format!("    [{yaw:#010x}, {pitch:#010x}],\n")).collect();
    assert_eq!(actual.as_slice(), ANGLES, "the table on this target:\n[\n{printed}]");
}

